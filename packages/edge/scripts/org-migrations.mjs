// Embeds drizzle-kit's SQL files in src/org/db/migrations.ts, which the Worker bundles. Run after changing the schema:
//   npx drizzle-kit generate && node scripts/org-migrations.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const db = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/org/db');
const files = readdirSync(path.join(db, 'sql')).filter((f) => f.endsWith('.sql')).sort();
const items = files.map((f) => JSON.stringify(readFileSync(path.join(db, 'sql', f), 'utf8')));
writeFileSync(path.join(db, 'migrations.ts'), `// Generated by scripts/org-migrations.mjs.\nexport const ORG_MIGRATIONS: string[] = [\n${items.join(',\n')},\n];\n`);
