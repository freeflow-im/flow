// Bundles the built-in help (src/help) into the Worker, which has no files to read: every docs/help/*.md as written, and
// "What's New" made by scripts/build-features.mjs from changelog/, as the server makes it per request. Writes
// src/help/bundle.generated.ts (gitignored) only when it changes, so `wrangler dev`, which runs this as its build, does not loop.
// Runs before wrangler dev and deploy (wrangler.toml [build]) and before typecheck and test (package.json).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const edge = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(edge, '../..');
const helpDir = path.join(root, 'docs', 'help');
const out = path.join(edge, 'src', 'help', 'bundle.generated.ts');

const files = {};
for (const name of fs.readdirSync(helpDir).sort()) {
  if (name.endsWith('.md')) files[name.slice(0, -3)] = fs.readFileSync(path.join(helpDir, name), 'utf8');
}
const { buildFeatures } = await import(pathToFileURL(path.join(root, 'scripts', 'build-features.mjs')).href);
const features = String(buildFeatures(root).markdown);

const text = `// Generated by scripts/help.mjs from docs/help and changelog/. Do not edit.
/** Each docs/help file's text, by its name without .md. */
export const HELP_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};
/** The "What's New" page: FEATURES.md as scripts/build-features.mjs makes it. */
export const FEATURES_MARKDOWN: string | null = ${JSON.stringify(features)};
`;
const before = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
if (before !== text) fs.writeFileSync(out, text);
console.log(`help: ${Object.keys(files).length} pages and What's New${before === text ? ' (unchanged)' : ''}`);
